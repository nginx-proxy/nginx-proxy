#!/usr/bin/env bash
# Generate /etc/nginx/conf.d/cloudflare.conf (set_real_ip_from + CF-Connecting-IP) from
# Cloudflare's published IP ranges.
#
# Never makes things worse: if a download fails or returns something that does not look
# like Cloudflare's list, the existing file is kept untouched.
#
# Exit codes: 0 = file written/changed, 3 = unchanged, 1 = error (existing file kept).
set -uo pipefail

TARGET_CONF="${CF_REAL_IP_CONF:-/etc/nginx/conf.d/cloudflare.conf}"
CF_V4_URL="${CF_V4_URL:-https://www.cloudflare.com/ips-v4}"
CF_V6_URL="${CF_V6_URL:-https://www.cloudflare.com/ips-v6}"
# Cloudflare currently publishes ~15 IPv4 and ~7 IPv6 ranges; far fewer means a bad response.
CF_MIN_V4="${CF_MIN_V4:-5}"
CF_MIN_V6="${CF_MIN_V6:-3}"

log() { echo "[cf-real-ip] $*" >&2; }

fetch() {
  curl -fsS --connect-timeout 10 --max-time "${CF_FETCH_MAX_TIME:-20}" \
    --retry "${CF_FETCH_RETRIES:-2}" --retry-delay 3 --retry-all-errors "$1"
}

v4_raw="$(fetch "${CF_V4_URL}")" || { log "failed to fetch ${CF_V4_URL}, keeping existing config"; exit 1; }
v6_raw="$(fetch "${CF_V6_URL}")" || { log "failed to fetch ${CF_V6_URL}, keeping existing config"; exit 1; }

# Keep only well-formed CIDRs (strip CR, blank lines, anything else), sorted for a stable output.
v4="$(printf '%s\n' "${v4_raw}" | tr -d '\r' | grep -E '^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$' | sort -u)"
v6="$(printf '%s\n' "${v6_raw}" | tr -d '\r' | grep -iE '^[0-9a-f:]+:[0-9a-f:]*/([0-9]|[1-9][0-9]|1[01][0-9]|12[0-8])$' | sort -u)"
v4_count="$(printf '%s' "${v4}" | grep -c . || true)"
v6_count="$(printf '%s' "${v6}" | grep -c . || true)"

if [ "${v4_count}" -lt "${CF_MIN_V4}" ] || [ "${v6_count}" -lt "${CF_MIN_V6}" ]; then
  log "unexpected response (${v4_count} IPv4 / ${v6_count} IPv6 ranges), keeping existing config"
  exit 1
fi

mkdir -p "$(dirname "${TARGET_CONF}")"
# Not *.conf so nginx never includes a half-written file (busybox mktemp needs a trailing XXXXXX).
tmp_conf="$(mktemp "${TARGET_CONF%.conf}.tmp.XXXXXX")" || { log "cannot create temp file"; exit 1; }
trap 'rm -f "${tmp_conf}"' EXIT

# No timestamp in the content: unchanged ranges must give an identical file (no needless reload).
{
  echo "# Auto-generated by update-cloudflare-real-ip.sh, do not edit."
  echo "# Source: ${CF_V4_URL} and ${CF_V6_URL}"
  echo ""
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
  echo ""
  echo "# Cloudflare IPv4 ranges"
  printf '%s\n' "${v4}" | sed 's/^/set_real_ip_from /; s/$/;/'
  echo ""
  echo "# Cloudflare IPv6 ranges"
  printf '%s\n' "${v6}" | sed 's/^/set_real_ip_from /; s/$/;/'
} >"${tmp_conf}" || { log "cannot write ${tmp_conf}"; exit 1; }

if [ -f "${TARGET_CONF}" ] && cmp -s "${tmp_conf}" "${TARGET_CONF}"; then
  exit 3
fi

chmod 644 "${tmp_conf}"
mv -f "${tmp_conf}" "${TARGET_CONF}" || { log "cannot replace ${TARGET_CONF}"; exit 1; }
log "updated ${TARGET_CONF} (${v4_count} IPv4 / ${v6_count} IPv6 ranges)"
exit 0
